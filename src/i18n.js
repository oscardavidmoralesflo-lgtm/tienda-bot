export const DICT = { es: ES, en: EN };
export const normLang = (l) => (l === 'en' ? 'en' : 'es');

export function t(lang, key, vars = {}) {
  const d = DICT[normLang(lang)];
  const s = d[key] ?? ES[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

// Mensaje de error de la API traducido (o el original si no está en el diccionario)
export function errorText(e, lang) {
  if (e?.code && DICT.es[`err_${e.code}`]) return t(lang, `err_${e.code}`);
  if (e?.status === 409) return t(lang, 'err_out_of_stock');
  return e?.message || t(lang, 'generic_error');
}

// Nombres de productos agrupados: traduce las palabras en español al inglés
const NAME_EN = [
  [/\bMeses\b/g, 'Months'], [/\bMes\b/g, 'Month'], [/\bAño\b/g, 'Year'], [/\bAños\b/g, 'Years'],
  [/\(Sin garantía\)/g, '(No warranty)'], [/\bCuentas\b/g, 'Accounts'], [/\bCréditos\b/g, 'Credits'],
  [/Billón de Tokens/g, 'Billion Tokens'], [/\(Código\)/g, '(Code)'], [/\(Invitación\)/g, '(Invite)'],
];
export function localName(name, lang) {
  if (normLang(lang) !== 'en' || !name) return name;
  return NAME_EN.reduce((s, [re, to]) => s.replace(re, to), String(name));
}

// Idioma guardado de un usuario (para avisos que no vienen de un mensaje)
const langCache = new Map();
export async function userLang(id) {
  if (langCache.has(id)) return langCache.get(id);
  const r = await one('SELECT lang FROM users WHERE id=$1', [id]).catch(() => null);
  const l = normLang(r?.lang);
  langCache.set(id, l);
  return l;
}
export const rememberLang = (id, lang) => langCache.set(id, normLang(lang));
